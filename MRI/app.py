    "class ResBlock(nn.Module):\n",
    "    def __init__(self, in_ch, out_ch):\n",
    "        super().__init__()\n",
    "        self.block = nn.Sequential(\n",
    "            nn.Conv3d(in_ch, out_ch, 3, padding=1, bias=False),\n",
    "            nn.BatchNorm3d(out_ch), nn.GELU(),\n",
    "            nn.Conv3d(out_ch, out_ch, 3, padding=1, bias=False),\n",
    "            nn.BatchNorm3d(out_ch)\n",
    "        )\n",
    "        self.skip = nn.Sequential(\n",
    "            nn.Conv3d(in_ch, out_ch, 1, bias=False),\n",
    "            nn.BatchNorm3d(out_ch)\n",
    "        ) if in_ch != out_ch else nn.Identity()\n",
    "        self.act = nn.GELU()\n",
    "    def forward(self, x): return self.act(self.block(x) + self.skip(x))\n",
    "\n",
    "class ResUNet3D(nn.Module):\n",
    "    def __init__(self, in_ch=1):\n",
    "        super().__init__()\n",
    "        self.enc1 = ResBlock(in_ch, 32); self.enc2 = ResBlock(32, 64)\n",
    "        self.enc3 = ResBlock(64, 128); self.enc4 = ResBlock(128, 256)\n",
    "        self.pool = nn.MaxPool3d(2)\n",
    "        self.bottleneck = ResBlock(256, 512)\n",
    "        self.up4 = nn.ConvTranspose3d(512, 256, 2, stride=2); self.dec4 = ResBlock(512, 256)\n",
    "        self.up3 = nn.ConvTranspose3d(256, 128, 2, stride=2); self.dec3 = ResBlock(256, 128)\n",
    "        self.up2 = nn.ConvTranspose3d(128, 64, 2, stride=2); self.dec2 = ResBlock(128, 64)\n",
    "        self.up1 = nn.ConvTranspose3d(64, 32, 2, stride=2); self.dec1 = ResBlock(64, 32)\n",
    "        self.seg_out = nn.Conv3d(32, 1, 1)\n",
    "    def forward(self, x):\n",
    "        e1 = self.enc1(x); e2 = self.enc2(self.pool(e1)); e3 = self.enc3(self.pool(e2)); e4 = self.enc4(self.pool(e3))\n",
    "        b = self.bottleneck(self.pool(e4))\n",
    "        d4 = self.dec4(torch.cat([self.up4(b), e4], dim=1))\n",
    "        d3 = self.dec3(torch.cat([self.up3(d4), e3], dim=1))\n",
    "        d2 = self.dec2(torch.cat([self.up2(d3), e2], dim=1))\n",
    "        d1 = self.dec1(torch.cat([self.up1(d2), e1], dim=1))\n",
    "        return torch.sigmoid(self.seg_out(d1))\n",
    "\n",
    "class ResBlock3D(nn.Module):\n",
    "    def __init__(self, in_ch, out_ch, stride=1):\n",
    "        super().__init__()\n",
    "        self.block = nn.Sequential(\n",
